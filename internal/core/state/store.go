// Package state reads and writes the machines' state files.
package state

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/josemiguelo/loadout/internal/core/coremodel"
	"github.com/josemiguelo/loadout/internal/model"
)

// StateStore reads and writes `<state>/<machine>.json` files inside the
// config repo, where stateDirName is the `layout state` directory. Each
// machine only ever writes its own file; all files are read for diffing. A
// child repo's parent's store is read-only (contract 18): a write to it is a bug.
type StateStore struct {
	stateDirName string
	stateDir     string
	readOnly     bool
	lastWarnings []string
}

// NewStateStore is the store of the repo at repoRoot.
func NewStateStore(repoRoot, stateDirName string, readOnly bool) *StateStore {
	return &StateStore{stateDirName: stateDirName, stateDir: filepath.Join(repoRoot, stateDirName), readOnly: readOnly}
}

// LastWarnings is the warnings from the most recent Read/ReadAll (e.g. files
// written by a newer loadout).
func (s *StateStore) LastWarnings() []string { return s.lastWarnings }

// PathFor is machine's state file.
func (s *StateStore) PathFor(machine string) string {
	return filepath.Join(s.stateDir, machine+".json")
}

// Read is machine's state, or nil when it has none (or it can't be used:
// see LastWarnings).
func (s *StateStore) Read(machine string) *coremodel.MachineState {
	s.lastWarnings = nil
	path := s.PathFor(machine)
	if _, err := os.Stat(path); err != nil {
		return nil
	}
	return s.decode(path)
}

// ReadAll is every machine state in the repo, keyed by machine name, in file name order.
func (s *StateStore) ReadAll() model.Map[coremodel.MachineState] {
	s.lastWarnings = nil
	var all model.Map[coremodel.MachineState]
	entries, err := os.ReadDir(s.stateDir)
	if err != nil {
		if !errors.Is(err, fs.ErrNotExist) {
			s.lastWarnings = append(s.lastWarnings, fmt.Sprintf("%s is not readable (%v)", s.stateDirName, err))
		}
		return all
	}
	var names []string
	for _, e := range entries {
		if strings.HasSuffix(e.Name(), ".json") {
			names = append(names, e.Name())
		}
	}
	slices.Sort(names)
	for _, name := range names {
		if state := s.decode(filepath.Join(s.stateDir, name)); state != nil {
			all.Set(state.Machine, *state)
		}
	}
	return all
}

// decode reads one state file, or nil with a warning when it can't be used.
// State is generated and disposable, so a file we can't read is a warning
// and a skip — never a crash (contract 9) and never silence (the machine
// would just vanish from `diff`).
func (s *StateStore) decode(path string) *coremodel.MachineState {
	name := filepath.Base(path)
	data, err := os.ReadFile(path)
	var state coremodel.MachineState
	if err == nil {
		state, err = Decode(string(data))
	}
	if err != nil {
		first, _, _ := strings.Cut(err.Error(), "\n")
		s.lastWarnings = append(s.lastWarnings, fmt.Sprintf(
			"%s/%s is not readable state (%s) — ignoring it; it is regenerated by `loadout status` on that machine",
			s.stateDirName, name, first))
		return nil
	}
	return s.accept(state, name)
}

// accept: a schemaVersion above ours means a newer loadout wrote the file;
// skip it rather than misinterpret it. Older/equal schemas load via
// defaults and ignored unknown keys.
func (s *StateStore) accept(state coremodel.MachineState, name string) *coremodel.MachineState {
	if state.SchemaVersion > coremodel.SchemaVersion {
		s.lastWarnings = append(s.lastWarnings, fmt.Sprintf(
			"%s/%s was written by a newer loadout (schema %d > %d) — ignoring it; upgrade loadout to see this machine",
			s.stateDirName, name, state.SchemaVersion, coremodel.SchemaVersion))
		return nil
	}
	return &state
}

// Write writes state to its machine's file.
func (s *StateStore) Write(state coremodel.MachineState) error {
	if s.readOnly {
		return fmt.Errorf("a child repo never writes its parent's state (%s)", s.stateDir)
	}
	if err := os.MkdirAll(s.stateDir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(s.PathFor(state.Machine), []byte(Encode(state)), 0o644)
}

// WriteChanged writes state unless it says what previous (the file it
// refreshed, nil for none) did, its timestamp aside: updatedAt (and git
// history) stays put when nothing real changed (contract 8). It is the
// state now on disk.
func (s *StateStore) WriteChanged(previous *coremodel.MachineState, state coremodel.MachineState) (coremodel.MachineState, error) {
	if previous != nil {
		same := state
		same.UpdatedAt = previous.UpdatedAt
		if same.Equal(*previous) {
			return *previous, nil
		}
	}
	return state, s.Write(state)
}

// WriteIfChanged writes text to target unless it already holds it, so a
// compile that changed nothing shows nothing in git. Nothing lands outside
// repoRoot: a child's compile never writes into its parent (contract 18).
func WriteIfChanged(repoRoot, target, text string) error {
	root := strings.TrimRight(filepath.Clean(repoRoot), "/") + "/"
	if !strings.HasPrefix(filepath.Clean(target), root) {
		return fmt.Errorf("compile writes only under the repo root: %s", target)
	}
	if current, err := os.ReadFile(target); err == nil && string(current) == text {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return err
	}
	return os.WriteFile(target, []byte(text), 0o644)
}
