// The state module reads and writes the machines' state files.

import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { cleanPath, fileError, joinPath, sortStrings, trimRight } from "../../model/index.ts";
import { type MachineState, machineStateEqual, schemaVersion } from "../coremodel/coremodel.ts";
import { decode, encode } from "./codec.ts";

/**
 * StateStore reads and writes `<state>/<machine>.json` files inside the
 * config repo, where stateDirName is the `layout state` directory. Each
 * machine only ever writes its own file; all files are read for diffing. A
 * child repo's parent's store is read-only (contract 18): a write to it is a bug.
 */
export class StateStore {
  private readonly stateDir: string;
  private warnings: string[] = [];

  constructor(
    repoRoot: string,
    private readonly stateDirName: string,
    private readonly readOnly: boolean,
  ) {
    this.stateDir = joinPath(repoRoot, stateDirName);
  }

  /**
   * lastWarnings is the warnings from the most recent read/readAll (e.g.
   * files written by a newer loadout).
   */
  lastWarnings(): string[] {
    return this.warnings;
  }

  /** pathFor is machine's state file. */
  pathFor(machine: string): string {
    return joinPath(this.stateDir, machine + ".json");
  }

  /**
   * read is machine's state, or undefined when it has none (or it can't be
   * used: see lastWarnings).
   */
  read(machine: string): MachineState | undefined {
    this.warnings = [];
    const path = this.pathFor(machine);
    try {
      statSync(path);
    } catch {
      return undefined;
    }
    return this.decode(path);
  }

  /** readAll is every machine state in the repo, keyed by machine name, in file name order. */
  readAll(): Map<string, MachineState> {
    this.warnings = [];
    const all = new Map<string, MachineState>();
    let names: string[];
    try {
      names = readdirSync(this.stateDir);
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code !== "ENOENT") {
        this.warnings.push(`${this.stateDirName} is not readable (${fileError(e, "open", this.stateDir).message})`);
      }
      return all;
    }
    for (const name of sortStrings(names.filter((n) => n.endsWith(".json")))) {
      const state = this.decode(joinPath(this.stateDir, name));
      if (state !== undefined) all.set(state.machine, state);
    }
    return all;
  }

  /**
   * decode reads one state file, or undefined with a warning when it can't
   * be used. State is generated and disposable, so a file we can't read is
   * a warning and a skip — never a crash (contract 9) and never silence (the
   * machine would just vanish from `diff`).
   */
  private decode(path: string): MachineState | undefined {
    const name = path.slice(path.lastIndexOf("/") + 1);
    let state: MachineState;
    try {
      let text: string;
      try {
        text = readFileSync(path, "utf8");
      } catch (e) {
        throw fileError(e, undefined, path);
      }
      state = decode(text);
    } catch (e) {
      const first = (e instanceof Error ? e.message : String(e)).split("\n")[0];
      this.warnings.push(
        `${this.stateDirName}/${name} is not readable state (${first}) — ignoring it; it is regenerated by \`loadout status\` on that machine`,
      );
      return undefined;
    }
    return this.accept(state, name);
  }

  /**
   * accept: a schemaVersion above ours means a newer loadout wrote the
   * file; skip it rather than misinterpret it. Older/equal schemas load via
   * defaults and ignored unknown keys.
   */
  private accept(state: MachineState, name: string): MachineState | undefined {
    if (state.schemaVersion > schemaVersion) {
      this.warnings.push(
        `${this.stateDirName}/${name} was written by a newer loadout (schema ${state.schemaVersion} > ${schemaVersion}) — ignoring it; upgrade loadout to see this machine`,
      );
      return undefined;
    }
    return state;
  }

  /** write writes state to its machine's file; throws file errors worded as fileError words them. */
  write(state: MachineState): void {
    if (this.readOnly) throw new Error(`a child repo never writes its parent's state (${this.stateDir})`);
    try {
      mkdirSync(this.stateDir, { recursive: true, mode: 0o755 });
    } catch (e) {
      throw fileError(e, "mkdir");
    }
    const path = this.pathFor(state.machine);
    try {
      writeFileSync(path, encode(state), { mode: 0o644 });
    } catch (e) {
      throw fileError(e, "open", path);
    }
  }

  /**
   * writeChanged writes state unless it says what previous (the file it
   * refreshed, undefined for none) did, its timestamp aside: updatedAt (and
   * git history) stays put when nothing real changed (contract 8). It is
   * the state now on disk.
   */
  writeChanged(previous: MachineState | undefined, state: MachineState): MachineState {
    if (previous !== undefined && machineStateEqual({ ...state, updatedAt: previous.updatedAt }, previous)) return previous;
    this.write(state);
    return state;
  }
}

/** newStateStore is the store of the repo at repoRoot. */
export function newStateStore(repoRoot: string, stateDirName: string, readOnly: boolean): StateStore {
  return new StateStore(repoRoot, stateDirName, readOnly);
}

/**
 * writeIfChanged writes text to target unless it already holds it, so a
 * compile that changed nothing shows nothing in git. Nothing lands outside
 * repoRoot: a child's compile never writes into its parent (contract 18).
 */
export function writeIfChanged(repoRoot: string, target: string, text: string): void {
  const root = trimRight(cleanPath(repoRoot), "/") + "/";
  if (!cleanPath(target).startsWith(root)) throw new Error(`compile writes only under the repo root: ${target}`);
  try {
    if (readFileSync(target).equals(Buffer.from(text))) return;
  } catch {
    // not there yet, or unreadable: write it
  }
  const dir = dirname(target);
  try {
    mkdirSync(dir, { recursive: true, mode: 0o755 });
  } catch (e) {
    throw fileError(e, "mkdir");
  }
  try {
    writeFileSync(target, text, { mode: 0o644 });
  } catch (e) {
    throw fileError(e, "open", target);
  }
}
